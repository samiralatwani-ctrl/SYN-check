// Copies packages/label-extraction/src into supabase/functions/_shared (Deno needs explicit .ts imports and
// a local schema path). --check fails when the copy is stale, so the deployed function can't drift from the tested code.
import { readFileSync, writeFileSync, readdirSync, mkdirSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const PACKAGES = [['packages/label-extraction/src', 'supabase/functions/_shared/label-extraction'],
                  ['packages/visual/src', 'supabase/functions/_shared/visual']];
const header = (from) => `// GENERATED by scripts/sync-edge-shared.mjs from ${from} — do not edit.\n`;
const check = process.argv.includes('--check');
let stale = false;
for (const [from, to] of PACKAGES) {
  const src = join(root, from), dst = join(root, to);
  const files = from.includes('label-extraction')
    ? { 'label-extraction.schema.json': readFileSync(join(root, 'packages/schemas/label-extraction.schema.json'), 'utf8') } : {};
  for (const f of readdirSync(src).filter((f) => f.endsWith('.ts'))) {
    files[f] = header(from) + readFileSync(join(src, f), 'utf8')
      .replace(/from '(\.\/[^']+)'/g, "from '$1.ts'")
      .replace("'../../schemas/label-extraction.schema.json'", "'./label-extraction.schema.json'");
  }
  mkdirSync(dst, { recursive: true });
  for (const [name, content] of Object.entries(files)) {
    const p = join(dst, name);
    if (check) { if (!existsSync(p) || readFileSync(p, 'utf8') !== content) { console.error(`stale: ${p}`); stale = true; } }
    else writeFileSync(p, content);
  }
}
if (stale) process.exit(1);
