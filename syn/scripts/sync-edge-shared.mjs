// Copies packages/label-extraction/src into supabase/functions/_shared (Deno needs explicit .ts imports and
// a local schema path). --check fails when the copy is stale, so the deployed function can't drift from the tested code.
import { readFileSync, writeFileSync, readdirSync, mkdirSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const src = join(root, 'packages/label-extraction/src');
const dst = join(root, 'supabase/functions/_shared/label-extraction');
const header = '// GENERATED by scripts/sync-edge-shared.mjs from packages/label-extraction/src — do not edit.\n';
const files = { 'label-extraction.schema.json': readFileSync(join(root, 'packages/schemas/label-extraction.schema.json'), 'utf8') };
for (const f of readdirSync(src).filter((f) => f.endsWith('.ts'))) {
  files[f] = header + readFileSync(join(src, f), 'utf8')
    .replace(/from '(\.\/[^']+)'/g, "from '$1.ts'")
    .replace("'../../schemas/label-extraction.schema.json'", "'./label-extraction.schema.json'");
}
const check = process.argv.includes('--check');
let stale = false;
mkdirSync(dst, { recursive: true });
for (const [name, body] of Object.entries(files)) {
  const p = join(dst, name);
  if (check) { if (!existsSync(p) || readFileSync(p, 'utf8') !== body) { console.error(`stale: ${p}`); stale = true; } }
  else writeFileSync(p, body);
}
if (stale) process.exit(1);
